func Migrate(ctx context.Context, db *sqlx.DB) error {
	lock, err := db.BeginTxx(ctx, nil)
	if err != nil {
		return err
	}
	defer func(lock *sqlx.Tx) {
		_ = lock.Rollback()
	}(lock)
	if _, err := lock.ExecContext(ctx, `SELECT pg_advisory_xact_lock($1, $2)`, crawlLockNamespace, migrationLockID); err != nil {
		return err
	}
	var exists bool
	if err := lock.GetContext(ctx, &exists, `SELECT to_regclass('public.schema_migrations') IS NOT NULL`); err != nil {
		return err
	}
	var current int
	if exists {
		if err := lock.GetContext(ctx, &current, `SELECT COALESCE(MAX(version), 0) FROM public.schema_migrations WHERE module = $1`, moduleID); err != nil {
			return err
		}
	}
	latest := dbMigrations[len(dbMigrations)-1].Version
	if current > latest {
		return fmt.Errorf("modrinth: schema version %d is newer than supported version %d", current, latest)
	}
	if current == latest {
		return nil
	}
	if _, err := lock.ExecContext(ctx, `SELECT pg_advisory_xact_lock($1, $2)`, crawlLockNamespace, crawlLockID); err != nil {
		return err
	}
	if err := database.MigrateTx(ctx, lock, moduleID, dbMigrations); err != nil {
		return err
	}
	return lock.Commit()
}
